/**
 * Check if a recipe contains ingredients that conflict with pet restrictions.
 * Returns restriction reason if blocked, null if safe.
 */
export function getRecipeRestrictionReason(recipe: Recipe, petRestrictions: string[]): string | null {
  const ingredientNames = recipe.ingredients.map(i => i.name.toLowerCase());

  for (const restriction of petRestrictions) {
    if (restriction === "alergia_frango" || restriction === "chicken_allergy") {
      if (recipe.tags.includes("chicken_allergy")) return "Contém ingredientes derivados de frango";
      const chickenWords = ["frango", "galinha"];
      if (ingredientNames.some(n => chickenWords.some(w => n.includes(w)))) return "Contém ingredientes derivados de frango";
    }
    if (restriction === "alergia_bovina") {
      const beefWords = ["bovino", "bovina", "boi", "tutano"];
      if (ingredientNames.some(n => beefWords.some(w => n.includes(w)))) return "Contém ingredientes derivados de carne bovina";
    }
    if (restriction === "sensibilidade_gastrica") {
      // Don't block, but could warn
    }
    if (restriction === "problema_renal") {
      // High phosphorus recipes could be an issue but we don't block by default
    }
  }
  return null;
}
